"""R40: build the taste proposal in _src/mock-taste/ without touching the live site.

Copies index.html, projects/ and assets/ from the live site, then:
  1. writes assets/taste.css = auto overrides (no tiny tracked capitals, nothing under 13px, no soft 3-16px radius)
     generated from the live CSS, plus the hand-written restyle in taste-hand.css;
  2. patches the copied HTML: drops the 01/02/03 number tabs and the "LX-26" codes, links taste.css last.
Re-run any time: it always starts from a fresh copy of the live files.
Usage: python3 _src/capture/r40/make_mock.py
"""
import re, shutil, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
MOCK = ROOT / "_src" / "mock-taste"

# 1. fresh copy (keep the downloaded fonts)
fonts = {p.name: p.read_bytes() for p in (MOCK / "assets" / "fonts").glob("work-sans-*.woff2")}
for sub in ("projects", "assets"):
    if (MOCK / sub).exists():
        shutil.rmtree(MOCK / sub)
    shutil.copytree(ROOT / sub, MOCK / sub)
shutil.copy2(ROOT / "index.html", MOCK / "index.html")
for name, data in fonts.items():
    (MOCK / "assets" / "fonts" / name).write_bytes(data)

pages = [MOCK / "index.html"] + sorted((MOCK / "projects").glob("*.html"))

# 2. collect every CSS rule on the site: style.css plus the <style> blocks inside pages
css = [(ROOT / "assets" / "style.css").read_text()]
for p in pages:
    css += re.findall(r"<style[^>]*>(.*?)</style>", p.read_text(), re.S)
css = re.sub(r"/\*.*?\*/", "", "\n".join(css), flags=re.S)

# selectors that are drawings (SVG text in viewBox units, dots, markers): sizes there are not reading sizes
FIGURE = re.compile(r"fx-|\.lp-|lx-dot|lx-ring|svg|\btext\b|tr-pm|tr-box|an-n|\.wl|::marker|\.times")
auto = []
seen = set()
for sel, body in re.findall(r"([^{}@]+)\{([^{}]*)\}", css):
    sel = " ".join(sel.split())
    if not sel or sel.startswith(("from", "to")) or re.match(r"^[\d.%, ]+$", sel):
        continue
    out = []
    if re.search(r"text-transform:\s*uppercase", body):
        out.append("text-transform: none; letter-spacing: 0")
    m = re.search(r"(?<![-\w])font-size:\s*([\d.]+)px", body)
    if m and float(m.group(1)) < 13 and not FIGURE.search(sel):
        out.append("font-size: 13px")
    r = re.search(r"border-radius:\s*([\d.]+)px", body)
    if r and 3 <= float(r.group(1)) <= 16 and not FIGURE.search(sel):
        out.append("border-radius: 0")
    for decl in out:
        key = (sel, decl)
        if key not in seen:
            seen.add(key)
            auto.append(f"{sel} {{ {decl}; }}")

taste = ("/* R40 taste proposal. Generated by _src/capture/r40/make_mock.py — do not edit here. */\n"
         "/* A. automatic: tracked capitals -> sentence case, floor 13px, soft radius -> square */\n"
         + "\n".join(auto) + "\n\n/* B. hand-written restyle */\n" + (HERE / "taste-hand.css").read_text())
(MOCK / "assets" / "taste.css").write_text(taste)

# 3. patch the copied pages
for p in pages:
    s = p.read_text()
    if "http-equiv=\"refresh\"" in s:
        continue  # the builder-toolkit redirect
    s = re.sub(r'<span class="tab">\d+</span>', "", s)
    # the "Next project · LS-26" kicker folds into the name: "Next: LexiSpeak"
    s = re.sub(r'<span class="nx-k">[^<]*</span><span class="nx-name">', '<span class="nx-name">Next: ', s)
    href = "assets/taste.css" if p.parent == MOCK else "../assets/taste.css"
    s = s.replace("</body>", f'<link rel="stylesheet" href="{href}">\n</body>', 1)
    p.write_text(s)

print(f"mock written: {len(pages)} pages, {len(auto)} automatic rules")
