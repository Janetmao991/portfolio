"""R41: the taste mock, round 2. Still MOCK ONLY: writes _src/mock-taste/, never the live site.

Runs the R40 build first (fresh copy of the live site + taste.css), then layers R41 on top:
  1. assets/r41.css   project/research pages at the homepage width (1160px), figures re-flowed for it,
                      plus the hidden "before" states for the entrance motion;
  2. assets/r41.js    the entrance motion (IntersectionObserver, runs once, off with reduced motion);
  3. a tiny inline script in <head> that turns the motion on before first paint (and back off if r41.js never runs);
  4. slides.js        prev/next fade between slides instead of sliding;
  5. ai-terms.html    the reviewer's "✗" becomes words.
Usage: python3 _src/capture/r41/make_mock.py
"""
import json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
MOCK = ROOT / "_src" / "mock-taste"

subprocess.run([sys.executable, str(ROOT / "_src" / "capture" / "r40" / "make_mock.py")], check=True)

# What fades up on entry. One list feeds both the CSS (hidden before) and the JS (what to watch),
# so they can't drift apart. The question trees (.tr) keep their own draw-in from motion.js.
REVEAL = [
    ".lx-top > *", ".title > *",                        # title + summary, on load
    ".lx-h > h2", ".lx-h > p",                          # highlight heading + text
    ".lx-pic", ".lp", ".lx-coda", ".lx-foot",           # highlight figures, the loop drawing, the closing lines
    "main > .plate > .ph", ".intro-l", ".posts li",     # research lists
    ".doc-page", ".pg", ".ss", ".tp-sheet", ".see",     # research figures
    "main > .next",
]
SEL = ", ".join(REVEAL)

css = (HERE / "r41.css").read_text().replace("/*REVEAL*/", SEL)
(MOCK / "assets" / "r41.css").write_text("/* R41. Generated by _src/capture/r41/make_mock.py from r41.css — do not edit here. */\n" + css)
js = (HERE / "r41.js").read_text().replace("__REVEAL__", json.dumps(SEL))
(MOCK / "assets" / "r41.js").write_text(js)

# runs in <head>, before first paint: motion on (unless reduced motion / no observer); if r41.js never
# arrives, take the class off again after 2.5s so nothing can stay hidden
HEAD = ('<script>(function(h){if(matchMedia("(prefers-reduced-motion: reduce)").matches||!("IntersectionObserver" in window))return;'
        'h.classList.add("m41");setTimeout(function(){if(!window.R41)h.classList.remove("m41")},2500)})(document.documentElement)</script>')

pages = sorted((MOCK / "projects").glob("*.html"))
for p in pages:
    s = p.read_text()
    if 'http-equiv="refresh"' in s:
        continue
    s = s.replace("</head>", HEAD + "\n</head>", 1)
    s = s.replace('<link rel="stylesheet" href="../assets/taste.css">',
                  '<link rel="stylesheet" href="../assets/taste.css">\n<link rel="stylesheet" href="../assets/r41.css">\n'
                  '<script src="../assets/r41.js"></script>', 1)
    if p.name == "ai-terms.html":
        # the ✗ is the reviewer's "fails" mark from the Chinese review table (✓ pass / ✗ fail, then the suggestion)
        n = s.count(" · ✗ scissors")
        assert n == 1, f"✗ text not found ({n})"
        s = s.replace(" · ✗ scissors cutting paper, a coordinate pin, a cabinet with drawers",
                      ". Fails; draw instead: scissors cutting paper, a coordinate pin, a cabinet with drawers")
    assert "✗" not in s, p.name
    p.write_text(s)

# the slideshow: buttons and arrow keys fade between slides (a swipe stays a native scroll)
sj = MOCK / "assets" / "slides.js"
s = sj.read_text()
old = '    track.scrollTo({ left: cur * track.clientWidth, behavior: smooth ? "smooth" : "instant" });\n    sync(cur);'
assert old in s, "slides.js changed upstream"
s = s.replace(old, '''    const jump = () => track.scrollTo({ left: cur * track.clientWidth, behavior: "instant" });
    // R41: fade out, jump, fade in (≈180ms + 320ms). Reduced motion or no change: just jump.
    if (!smooth || REDUCED || at() === cur) { jump(); sync(cur); return; }
    clearTimeout(fadeT);
    track.classList.add("ss-out");
    sync(cur);
    fadeT = setTimeout(() => { jump(); track.classList.remove("ss-out"); }, 180);''')
s = s.replace('  let cur = 0;\n', '  let cur = 0, fadeT;\n  const REDUCED = matchMedia("(prefers-reduced-motion: reduce)").matches;\n', 1)
sj.write_text(s)

print(f"R41 layered on {len(pages)} project pages")
